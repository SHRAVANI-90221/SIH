    function getCultureTranslation(region, language) {

        const data = cultureData[region];

        if (!data) {
            return {};
        }

        const lang = language || "en-IN";

        if (lang.startsWith("hi")) {
            return {
                name: data.name,
                text: data.hindi,
                festival: data.festivalHi,
                dance: data.danceHi,
                music: data.musicHi,
                game: data.gameHi,
                food: data.foodHi,
                song: data.song
            };
        }

        if (lang.startsWith("mr")) {
            return {
                name: data.name,
                text: data.marathi,
                festival: data.festivalMr,
                dance: data.danceMr,
                music: data.musicMr,
                game: data.gameMr,
                food: data.foodMr,
                song: data.song
            };
        }

        return {
            name: data.name,
            text: data.text,
            festival: data.festival,
            dance: data.dance,
            music: data.music,
            game: data.game,
            food: data.food,
            song: data.song
        };
    }


